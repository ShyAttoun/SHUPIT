import puppeteer from 'puppeteer-core';
const BASE = process.argv[2];
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 420, height: 900, isMobile: true });
const bad = [];
p.on('console', (m) => { const t = m.text(); if (/Content Security Policy|Refused to/.test(t)) bad.push(t.slice(0, 160)); });
let popup = null;
b.on('targetcreated', (t) => { if (t.type() === 'page') popup = t.url(); });
await p.goto(BASE + '/', { waitUntil: 'networkidle2' });
await p.screenshot({ path: '/tmp/signin.png' });
const g = await p.waitForSelector('xpath/.//*[@role="button"][contains(normalize-space(.),"Continue with Google") or contains(normalize-space(.),"המשך עם Google")]', { timeout: 15000 });
await g.click();
await new Promise((r) => setTimeout(r, 4000));
console.log('csp violations:', bad.length); bad.forEach((x) => console.log(' -', x));
const pages = await b.pages();
console.log('pages after click:', (await Promise.all(pages.map((x) => x.url()))).map((u) => u.slice(0, 90)));
console.log('page text:', (await p.evaluate(() => document.body.innerText)).replace(/\s+/g,' ').slice(0,300));
await b.close();
